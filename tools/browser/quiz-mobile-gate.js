async (page) => {
  const check=(ok,message)=>{if(!ok)throw new Error(message);};
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const correctChoices={'tail-balance':'b','dusk-activity':'a','bamboo-energy':'c','panda-family':'b','wildlife-watching':'a','forest-links':'c'};
  const capture=async(id,path)=>{await page.locator(id).evaluate(node=>node.scrollIntoView({block:'start'}));await page.waitForTimeout(350);await page.screenshot({path});};
  page.setDefaultTimeout(20000);
  await page.waitForFunction(()=>window.helpaniPatrol?.state());
  const mobile=await page.evaluate(()=>({width:innerWidth,height:innerHeight,touchPoints:navigator.maxTouchPoints,dpr:devicePixelRatio,coarse:matchMedia('(pointer:coarse)').matches}));
  check(mobile.width===393&&mobile.touchPoints>0&&mobile.coarse,'Mobile touch context required');
  await page.getByRole('combobox',{name:'这次想找什么？'}).selectOption('habitat');
  await page.getByRole('button',{name:'出发巡护',exact:true}).tap();
  await page.waitForFunction(()=>helpaniPatrol.state().runId);
  await page.getByRole('button',{name:'掷骰前进',exact:true}).tap();
  await page.waitForFunction(()=>helpaniPatrol.state().pendingEvent?.kind==='quiz'&&!document.querySelector('#patrol-event').hidden);
  const first=await page.evaluate(()=>helpaniPatrol.state().pendingEvent);
  check(first.choices.length===3,'Question does not offer three choices');
  check(!('correctChoiceId' in first)&&!('explanation' in first)&&!('source' in first),'Pending event leaks answer');
  await capture('#patrol-event','output/playwright/quiz/mobile-question.png');
  const wrong=first.choices.find(choice=>choice.id!==correctChoices[first.questionId]);
  await page.getByRole('button',{name:wrong.label,exact:true}).tap();
  await page.waitForFunction(()=>helpaniPatrol.state().lastResult?.quiz&&!helpaniPatrol.state().pendingEvent);
  const result=await page.evaluate(()=>helpaniPatrol.state().lastResult.quiz);
  check(result.correct===false,'Wrong answer branch was not exercised');
  check(await page.locator('.patrol-fact-answer').textContent()===result.correctAnswer,'Correct answer absent');
  check((await page.locator('#patrol-quiz-feedback').textContent()).includes(result.explanation),'Explanation absent');
  check((await page.locator('#patrol-quiz-feedback .patrol-fact-source a').getAttribute('href')).startsWith('https://'),'Source is not HTTPS');
  check((await page.locator('.patrol-observation-prompt').textContent()).includes(result.observationPrompt),'Observation prompt absent');
  await capture('#patrol-result','output/playwright/quiz/mobile-answer.png');
  await page.locator('#patrol-result').screenshot({path:'output/playwright/quiz/mobile-answer-card.png'});
  check(!(await page.locator('#patrol-next').isHidden()),'Wrong answer prevented continuing');
  await page.getByRole('button',{name:'回林地找找看',exact:true}).tap();
  await page.waitForFunction(()=>document.querySelector('#wood-notice').textContent.startsWith('观察线索：'));
  check((await page.locator('#wood-notice').textContent()).includes(result.observationPrompt),'Return lost question clue');
  await page.waitForFunction(()=>document.querySelector('#wood-canvas').getBoundingClientRect().top<innerHeight);
  const beforeNext=await page.evaluate(()=>helpaniPatrol.state().remaining);
  await page.getByRole('button',{name:'继续巡护 · 掷骰',exact:true}).tap();
  await page.waitForFunction(()=>helpaniPatrol.state().pendingEvent?.kind==='quiz'&&!document.querySelector('#patrol-event').hidden);
  const second=await page.evaluate(()=>helpaniPatrol.state().pendingEvent);
  check(second.id!==first.id&&second.questionId!==first.questionId,'Next question repeated first unseen question');
  check(await page.evaluate(()=>helpaniPatrol.state().remaining)===beforeNext-1,'Continue action consumed wrong number of dice');
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForFunction(id=>window.helpaniPatrol?.state()?.pendingEvent?.id===id,second.id);
  check(await page.evaluate(()=>JSON.stringify(helpaniPatrol.state().pendingEvent))===JSON.stringify(second),'Pending question or choice order changed after reload');
  await page.getByRole('button',{name:second.choices.find(choice=>choice.id===correctChoices[second.questionId]).label,exact:true}).tap();
  await page.waitForFunction(()=>helpaniPatrol.state().lastResult?.quiz?.correct&&!helpaniPatrol.state().pendingEvent);
  const beforeReload=await page.evaluate(()=>helpaniPatrol.state());
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.helpaniPatrol?.state()?.knowledge.length===2);
  check(await page.evaluate(()=>helpaniPatrol.state().knowledge.length)===2,'Knowledge did not restore');
  await page.locator('.patrol-knowledge>summary').tap();
  await page.waitForFunction(()=>document.querySelector('.patrol-knowledge').open);
  check(await page.locator('#patrol-knowledge-grid article').count()===2,'Knowledge cards missing');
  check(await page.locator('#patrol-knowledge-grid .patrol-fact-source a').count()===2,'Knowledge sources missing');
  await capture('.patrol-knowledge','output/playwright/quiz/mobile-knowledge.png');
  check(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth),'Mobile overflow');
  check(errors.length===0,'Uncaught page errors: '+errors.join(', '));
  return {engine:'Google Chrome mobile/touch emulation, not physical iOS or Safari',mobile,questionChoices:3,pendingAnswerHidden:true,wrongAnswerExplained:true,wrongAnswerCanContinue:true,correctAnswerFeedback:true,sourceVisible:true,observationClueReturned:true,continueConsumedOneDie:true,pendingQuestionAndChoiceOrderRestored:true,knowledgeRestored:2,positionAfterReload:beforeReload.position,completedAfterTwoAnswers:beforeReload.completed,horizontalOverflowAbsent:true,pageErrors:errors};
}
